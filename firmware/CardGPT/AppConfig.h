struct WifiCredentials {
  String ssid;
  String password;

  bool valid() const { return !ssid.isEmpty(); }
};

struct OAuthCredentials {
  String accessToken;
  String refreshToken;
  String idToken;
  String accountId;
  uint64_t accessTokenExpiresAt = 0;

  bool valid() const {
    return !accessToken.isEmpty() && !refreshToken.isEmpty() && !accountId.isEmpty();
  }
};

struct UserSettings {
  String textModel = kTextModelTerra;
  String reasoningEffort = "low";
  String language = "es";

  bool english() const { return language == "en"; }
};

struct ModelOption {
  String slug;
  String displayName;
  String defaultReasoning;
  String reasoningLevels[kMaxReasoningLevels];
  size_t reasoningLevelCount = 0;

  bool supportsReasoning(const String& effort) const {
    for (size_t i = 0; i < reasoningLevelCount; ++i) {
      if (reasoningLevels[i] == effort) return true;
    }
    return false;
  }
};

struct ModelCatalog {
  ModelOption models[kMaxAvailableModels];
  size_t count = 0;
  bool live = false;

  void clear() {
    for (size_t i = 0; i < count; ++i) models[i] = ModelOption();
    count = 0;
    live = false;
  }

  int indexOf(const String& slug) const {
    for (size_t i = 0; i < count; ++i) {
      if (models[i].slug == slug) return static_cast<int>(i);
    }
    return -1;
  }

  const ModelOption* find(const String& slug) const {
    const int index = indexOf(slug);
    return index < 0 ? nullptr : &models[index];
  }
};

struct ChatMessage {
  bool fromUser = false;
  String text;
};

